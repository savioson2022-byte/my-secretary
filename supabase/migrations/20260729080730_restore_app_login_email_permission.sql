-- 이전 마이그레이션(20260729000000_security_hardening.sql)에서
-- 이메일 열거 공격을 방지하기 위해 anon 권한을 회수했으나,
-- 이로 인해 현재 클라이언트 기반의 아이디 로그인이 차단되는 문제가 발생했습니다.
--
-- 기존 로그인 기능을 보존하기 위해 해당 권한을 다시 복구합니다.
--
-- [후속 과제]
-- 향후 아이디 로그인은 클라이언트에서 이메일 조회를 분리하고,
-- 서버 전용 로그인 API(Route Handler)를 통해 쿠키를 안전하게 발급받는 방식으로
-- 구조를 개선해야 합니다. 그 후 이 권한을 다시 제거해야 합니다.

grant execute on function public.resolve_app_login_email(text) to anon, authenticated;
