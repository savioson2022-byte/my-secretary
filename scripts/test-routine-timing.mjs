import assert from 'node:assert/strict';
import ts from 'typescript';
import { readFileSync } from 'node:fs';
const source = ts.transpileModule(readFileSync(new URL('../src/lib/routineTiming.ts', import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
const { changeRoutineTiming } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const base = { title: '고1 2반', startTime: '17:00', endTime: '18:00', placeName: '학원', memo: '교재', travelMode: 'transit', cancelledDates: ['2026-11-05'], startDate: null, endDate: null, isActive: true, createdAt: 'original', updatedAt: 'original' };
const tue = { ...base, id: 'tue', dayOfWeek: '화' };
const thu = { ...base, id: 'thu', dayOfWeek: '목' };
const rows = [tue, thu];
const before = structuredClone(rows);
const timing = { dayOfWeek: '일', startTime: '17:00', endTime: '18:00' };
const result = changeRoutineTiming(rows, thu, timing, 'now');
assert.deepEqual(rows, before);
assert.deepEqual(result, { ...thu, ...timing, updatedAt: 'now' });
assert.throws(() => changeRoutineTiming(rows, thu, { ...timing, endTime: '' }));
assert.throws(() => changeRoutineTiming(rows, thu, { ...timing, endTime: '16:00' }));
assert.throws(() => changeRoutineTiming(rows, thu, { ...timing, dayOfWeek: '화' }));
assert.throws(() => changeRoutineTiming([tue], thu, timing));
assert.throws(() => changeRoutineTiming([tue, { ...thu, memo: '변경됨' }], thu, timing));
const dated = { ...thu, startDate: '2026-01-01' };
assert.equal(changeRoutineTiming([tue, dated, { ...result, id: 'old', endDate: '2025-01-01' }], dated, timing).dayOfWeek, '일');
console.log('routine timing: 8 checks passed');
